// Browser check of the crafting flow: stand at a bench, press E, craft a pistol.
import { chromium } from 'playwright-core';
import fs from 'node:fs';
import { startServer } from '../server/index.js';

const out = 'tests/output/craft';
fs.mkdirSync(out, { recursive: true });
const srv = await startServer({ port: 0, dbFile: ':memory:', quiet: true, noSignals: true, matchConfig: { voteSeconds: 2, countdownSeconds: 1, durations: { craft: 120 } } });
const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || '/opt/pw-browsers/chromium', args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] });
const page = await browser.newPage({ viewport: { width: 1280, height: 720 } });
const errors = [];
page.on('pageerror', (e) => errors.push(e.message));
await page.addInitScript(() => { window.__YOINK_TEST__ = true; });
await page.goto(`http://localhost:${srv.port}`);
await page.click('text=Create account');
await page.fill('#auth-user', 'crafter');
await page.fill('#auth-pass', 'secret123');
await page.fill('#auth-pass2', 'secret123');
await page.click('#auth-submit');
await page.waitForSelector('#btn-practice');
await page.click('.mode-card[data-mode="craft"]');
await page.click('#btn-practice');
await page.waitForSelector('.map-card');
await page.click('.map-card[data-map="forest"]');
await page.waitForFunction(() => window.__yoink.game && window.__yoink.game.state === 'playing', null, { timeout: 30000 });
// Test harness (server side): put the player next to a bench and give materials.
const match = [...srv.services.matchmaking.matches.values()][0];
const me = match.humans()[0];
const bench = match.map.benches[0];
const dirs = [[0, -1.5], [1.5, 0], [0, 1.5], [-1.5, 0]];
const [ox, oz] = [[0, 1.4], [-1.4, 0], [0, -1.4], [1.4, 0]][bench.r & 3];
match.placePlayer(me, bench.x + ox, bench.y + 0.02, bench.z + oz, Math.atan2(ox, oz));
Object.assign(me.inv.mats, { wood: 10, scrap: 20, parts: 6, gunpowder: 4, cloth: 6, electronics: 2, rare: 1 });
match.sendInv(me);
void dirs;
await page.waitForTimeout(800);
await page.keyboard.press('KeyE');
await page.waitForSelector('.recipe', { timeout: 5000 });
await page.screenshot({ path: `${out}/01-bench.png` });
await page.click('.recipe:has-text("Pistol") >> button');
await page.waitForTimeout(500);
await page.click('.cat-tabs >> text=Ammo');
await page.click('.recipe:has-text("Light Ammo") >> button');
await page.waitForTimeout(500);
await page.screenshot({ path: `${out}/02-crafted.png` });
const inv = await page.evaluate(() => window.__yoink.game.inv);
console.log('slots', JSON.stringify(inv.slots), 'ammo', inv.ammo.light, 'scrap', inv.mats.scrap);
await page.keyboard.press('KeyI');
await page.waitForTimeout(300);
await page.screenshot({ path: `${out}/03-holding.png` });
console.log('server inv', JSON.stringify(me.inv.slots), 'crafted', me.stats.crafted, 'errors', errors);
await browser.close();
await srv.close();
process.exit(0);
