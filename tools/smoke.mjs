// Quick browser smoke test: register, start a practice match, play a bit, screenshot.
import { chromium } from 'playwright-core';
import { startServer } from '../server/index.js';
import fs from 'node:fs';

const mode = process.argv[2] || 'tag';
const out = process.argv[3] || 'tests/output';
fs.mkdirSync(out, { recursive: true });
const dbFile = `${out}/smoke-${Date.now()}.db`;
const srv = await startServer({ port: 0, dbFile, quiet: true, noSignals: true });
const url = `http://localhost:${srv.port}`;
const browser = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium', args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] });
const page = await browser.newPage({ viewport: { width: 1280, height: 720 } });
const errors = [];
page.on('console', (m) => { if (m.type() === 'error' || m.type() === 'warning') errors.push(`[${m.type()}] ${m.text()}`); });
page.on('pageerror', (e) => errors.push('[pageerror] ' + e.message));
await page.addInitScript(() => { window.__YOINK_TEST__ = true; });
await page.goto(url);
await page.screenshot({ path: `${out}/01-auth.png` });
await page.click('text=Create account');
const name = 'tester' + Math.floor(Math.random() * 9999);
await page.fill('#auth-user', name);
await page.fill('#auth-pass', 'secret123');
await page.fill('#auth-pass2', 'secret123');
await page.click('#auth-submit');
await page.waitForSelector('#btn-practice', { timeout: 10000 });
await page.screenshot({ path: `${out}/02-menu.png` });
await page.click(`.mode-card[data-mode="${mode}"]`);
await page.click('#btn-practice');
await page.waitForSelector('.map-card', { timeout: 10000 });
await page.click('.map-card[data-map="forest"]');
await page.waitForTimeout(500);
await page.screenshot({ path: `${out}/03-vote.png` });
await page.waitForFunction(() => window.__yoink.game && window.__yoink.game.state === 'countdown' || (window.__yoink.game && window.__yoink.game.state === 'playing'), null, { timeout: 30000 });
await page.waitForTimeout(1500);
await page.screenshot({ path: `${out}/04-countdown.png` });
await page.waitForFunction(() => window.__yoink.game && window.__yoink.game.state === 'playing', null, { timeout: 15000 });
await page.waitForTimeout(500);
await page.screenshot({ path: `${out}/05-playing.png` });
// walk forward
await page.keyboard.down('KeyW');
await page.waitForTimeout(1500);
await page.keyboard.up('KeyW');
const pos = await page.evaluate(() => { const g = window.__yoink.game; return { x: g.body.x, y: g.body.y, z: g.body.z, fps: g.renderer.info.render.calls }; });
console.log('position after walking', pos);
await page.evaluate(() => { const g = window.__yoink.game; g.yaw += Math.PI; });
await page.waitForTimeout(300);
await page.screenshot({ path: `${out}/06-turned.png` });
await page.mouse.click(640, 360);
await page.waitForTimeout(200);
await page.screenshot({ path: `${out}/07-punch.png` });
const info = await page.evaluate(() => { const g = window.__yoink.game; return { calls: g.renderer.info.render.calls, tris: g.renderer.info.render.triangles, players: [...g.players.values()].map((p) => [p.name, p.x.toFixed(1), p.z.toFixed(1), p.alive]) }; });
console.log(JSON.stringify(info));
console.log('ERRORS:\n' + errors.slice(0, 30).join('\n'));
await browser.close();
await srv.close();
process.exit(0);
